-- قاعدة بيانات كلية الأفق - Al-Ufuq College
-- جاهزة للعمل على خادم XAMPP (MySQL / MariaDB)

CREATE DATABASE IF NOT EXISTS `alufuq_college` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `alufuq_college`;

-- 1. جدول المستخدمين (الطلاب والإدارة)
DROP TABLE IF EXISTS `users`;
CREATE TABLE `users` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `username` VARCHAR(50) NOT NULL UNIQUE,
  `full_name` VARCHAR(100) NOT NULL,
  `email` VARCHAR(100) NOT NULL UNIQUE,
  `password` VARCHAR(255) NOT NULL,
  `role` ENUM('admin', 'student') NOT NULL DEFAULT 'student',
  `student_id` VARCHAR(30) DEFAULT NULL UNIQUE,
  `phone` VARCHAR(20) DEFAULT NULL,
  `department_id` INT DEFAULT NULL,
  `avatar` VARCHAR(255) DEFAULT 'default_avatar.png',
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. جدول الأقسام العلمية والأدبية
DROP TABLE IF EXISTS `departments`;
CREATE TABLE `departments` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `code` VARCHAR(10) NOT NULL UNIQUE,
  `name_ar` VARCHAR(100) NOT NULL,
  `name_en` VARCHAR(100) NOT NULL,
  `track_type` ENUM('علمي', 'أدبي', 'مشترك') NOT NULL,
  `icon` VARCHAR(50) NOT NULL DEFAULT 'fa-graduation-cap',
  `color_accent` VARCHAR(20) NOT NULL DEFAULT '#2563eb',
  `degree` VARCHAR(50) NOT NULL DEFAULT 'بكالوريوس (4 سنوات)',
  `min_percentage` DECIMAL(5,2) NOT NULL DEFAULT 65.00,
  `annual_fee` VARCHAR(50) NOT NULL DEFAULT 'مناسبة ومدعومة',
  `short_desc` TEXT NOT NULL,
  `full_desc` LONGTEXT NOT NULL,
  `career_opportunities` TEXT NOT NULL,
  `study_plan` TEXT NOT NULL,
  `image` VARCHAR(255) DEFAULT 'dept_default.jpg'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. جدول طلبات التقديم والقبول
DROP TABLE IF EXISTS `applications`;
CREATE TABLE `applications` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `app_number` VARCHAR(30) NOT NULL UNIQUE,
  `full_name` VARCHAR(100) NOT NULL,
  `gender` ENUM('ذكر', 'أنثى') NOT NULL,
  `national_id` VARCHAR(30) NOT NULL,
  `phone` VARCHAR(20) NOT NULL,
  `email` VARCHAR(100) NOT NULL,
  `address` VARCHAR(200) NOT NULL,
  `high_school_branch` ENUM('علمي', 'أدبي') NOT NULL,
  `seat_number` VARCHAR(30) NOT NULL,
  `graduation_year` INT NOT NULL DEFAULT 2026,
  `percentage` DECIMAL(5,2) NOT NULL,
  `department_id` INT NOT NULL,
  `notes` TEXT DEFAULT NULL,
  `status` ENUM('قيد المراجعة', 'مقبول مبدئياً', 'مقبول نهائياً', 'مرفوض', 'معلق للاستيفاء') NOT NULL DEFAULT 'قيد المراجعة',
  `admin_reply` TEXT DEFAULT NULL,
  `interview_date` DATE DEFAULT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`department_id`) REFERENCES `departments`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. جدول التقويم الدراسي
DROP TABLE IF EXISTS `academic_calendar`;
CREATE TABLE `academic_calendar` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `semester` VARCHAR(50) NOT NULL,
  `title` VARCHAR(150) NOT NULL,
  `category` ENUM('تسجيل وقبول', 'بداية دراسة', 'امتحانات', 'أنشطة وفعاليات', 'إجازات وعطل') NOT NULL,
  `start_date` DATE NOT NULL,
  `end_date` DATE DEFAULT NULL,
  `description` TEXT NOT NULL,
  `is_highlight` TINYINT(1) DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. جدول نتائج الامتحانات
DROP TABLE IF EXISTS `exam_results`;
CREATE TABLE `exam_results` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `student_id` VARCHAR(30) NOT NULL,
  `student_name` VARCHAR(100) NOT NULL,
  `seat_number` VARCHAR(30) NOT NULL,
  `academic_year` VARCHAR(20) NOT NULL DEFAULT '2025/2026',
  `semester` VARCHAR(50) NOT NULL,
  `department_id` INT NOT NULL,
  `course_code` VARCHAR(20) NOT NULL,
  `course_name` VARCHAR(100) NOT NULL,
  `credit_hours` INT NOT NULL DEFAULT 3,
  `coursework_grade` DECIMAL(5,2) NOT NULL,
  `final_grade` DECIMAL(5,2) NOT NULL,
  `total_grade` DECIMAL(5,2) NOT NULL,
  `letter_grade` VARCHAR(5) NOT NULL,
  `gpa_points` DECIMAL(3,2) NOT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`department_id`) REFERENCES `departments`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. جدول الأنشطة الطلابية
DROP TABLE IF EXISTS `activities`;
CREATE TABLE `activities` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `title` VARCHAR(150) NOT NULL,
  `category` ENUM('مبادرات طلابية', 'دورات كرة القدم', 'الأيام الثقافية', 'الحملات التوعوية', 'المشاركات الطلابية') NOT NULL,
  `organizer` VARCHAR(100) NOT NULL DEFAULT 'عمادة شؤون الطلاب',
  `event_date` DATE NOT NULL,
  `location` VARCHAR(100) NOT NULL,
  `description` LONGTEXT NOT NULL,
  `goals` TEXT DEFAULT NULL,
  `image` VARCHAR(255) DEFAULT 'activity_default.jpg',
  `registered_count` INT DEFAULT 0,
  `max_capacity` INT DEFAULT 100,
  `is_featured` TINYINT(1) DEFAULT 0,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 7. جدول مباريات دورة كرة القدم
DROP TABLE IF EXISTS `football_matches`;
CREATE TABLE `football_matches` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `tournament_title` VARCHAR(100) NOT NULL DEFAULT 'كأس الأفق السنوي لكرة القدم 2026',
  `team_a` VARCHAR(100) NOT NULL,
  `team_b` VARCHAR(100) NOT NULL,
  `score_a` INT DEFAULT NULL,
  `score_b` INT DEFAULT NULL,
  `match_date` DATETIME NOT NULL,
  `stage` VARCHAR(50) NOT NULL DEFAULT 'دور المجموعات',
  `stadium` VARCHAR(100) NOT NULL DEFAULT 'الملعب الرياضي الجامعي لكلية الأفق',
  `status` ENUM('قادمة', 'جارية الآن', 'انتهت') NOT NULL DEFAULT 'قادمة',
  `highlights` TEXT DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 8. جدول الشكاوى والمقترحات
DROP TABLE IF EXISTS `complaints`;
CREATE TABLE `complaints` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `ticket_number` VARCHAR(30) NOT NULL UNIQUE,
  `type` ENUM('شكوى طلابية', 'مقترح تطويري') NOT NULL,
  `category` ENUM('أكاديمي وتدريسي', 'مرافق وخدمات', 'جداول وامتحانات', 'أنشطة طلابية', 'شؤون مالية', 'أخرى') NOT NULL,
  `title` VARCHAR(150) NOT NULL,
  `content` LONGTEXT NOT NULL,
  `student_name` VARCHAR(100) DEFAULT 'طالب جامعي',
  `student_id` VARCHAR(30) DEFAULT NULL,
  `email` VARCHAR(100) DEFAULT NULL,
  `is_anonymous` TINYINT(1) DEFAULT 0,
  `status` ENUM('قيد المراجعة', 'قيد المعالجة', 'تم الحل والرد', 'مغلقة') NOT NULL DEFAULT 'قيد المراجعة',
  `admin_response` LONGTEXT DEFAULT NULL,
  `response_date` DATETIME DEFAULT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 9. جدول الاستعلامات والأسئلة الشائعة
DROP TABLE IF EXISTS `inquiries_faq`;
CREATE TABLE `inquiries_faq` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `question` VARCHAR(255) NOT NULL,
  `answer` LONGTEXT NOT NULL,
  `category` ENUM('شروط القبول', 'الرسوم والمنح', 'الأقسام والتخصصات', 'الوثائق المطلوبة', 'الأنشطة والخدمات', 'عام') NOT NULL,
  `views` INT DEFAULT 0,
  `keywords` VARCHAR(255) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 10. جدول تسجيل الطلاب في الأنشطة والمبادرات
DROP TABLE IF EXISTS `activity_signups`;
CREATE TABLE `activity_signups` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `activity_id` INT NOT NULL,
  `student_name` VARCHAR(100) NOT NULL,
  `student_id` VARCHAR(30) NOT NULL,
  `phone` VARCHAR(20) NOT NULL,
  `department` VARCHAR(100) NOT NULL,
  `notes` TEXT DEFAULT NULL,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`activity_id`) REFERENCES `activities`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

